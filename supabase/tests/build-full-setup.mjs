// Builds ../full_setup.sql = every migration (in order) + demo_logins.sql (empty store, demo logins only),
// so a brand-new Supabase project can be set up with ONE paste into the SQL editor.
// Run after editing any migration:  npm run build   (from supabase/tests)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const migrations = fs.readdirSync(path.join(root, 'migrations')).filter((f) => f.endsWith('.sql')).sort();

export function fullSetupParts() {
  return [
    ...migrations.map((f) => [`migrations/${f}`, fs.readFileSync(path.join(root, 'migrations', f), 'utf8')]),
    ['demo_logins.sql', fs.readFileSync(path.join(root, 'demo_logins.sql'), 'utf8')],
  ];
}

export function buildFullSetup() {
  const header = `-- =============================================================================
-- FULL SETUP — generated by tests/build-full-setup.mjs, do not edit by hand.
-- Paste into Supabase → SQL Editor → Run, on a NEW (empty) project.
-- Contains: ${migrations.length} migrations + demo_logins.sql. The store starts EMPTY
-- (no products, orders or customers) with one-click demo logins only.
-- Want sample products/orders to show a client? Run seed.sql afterwards.
-- =============================================================================
`;
  const body = fullSetupParts()
    .map(([name, sql]) => `\n-- >>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>\n-- ${name}\n-- >>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>\n${sql}`)
    .join('\n');
  const out = header + body;
  fs.writeFileSync(path.join(root, 'full_setup.sql'), out);
  return out;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  buildFullSetup();
  console.log('Wrote supabase/full_setup.sql');
}
